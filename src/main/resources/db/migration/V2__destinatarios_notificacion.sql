-- Casillas que reciben el aviso de "consulta nueva". Las administra el admin desde Mi Perfil.
-- Si la tabla está vacía, el aviso va a la casilla de respaldo (variable MAIL_ADMIN).
CREATE TABLE destinatario_notificacion (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail       VARCHAR(255) NOT NULL,
    fecha_alta TIMESTAMP(6) NOT NULL
);

-- Sin duplicados aunque cambien mayúsculas/minúsculas
CREATE UNIQUE INDEX uk_destinatario_notificacion_mail ON destinatario_notificacion (LOWER(mail));
