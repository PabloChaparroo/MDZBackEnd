-- Esquema inicial de MDZ Muebles (PostgreSQL).
-- Refleja las entidades @Entity actuales; se armo a partir del DDL que genera
-- Hibernate 6.4 para PostgreSQL. A partir de aca, cualquier cambio de entidad
-- necesita una migracion nueva (V2__..., V3__...): Hibernate corre con
-- ddl-auto=validate y no modifica el esquema.

CREATE TABLE categoria (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria             VARCHAR(255),
    fecha_alta_categoria         TIMESTAMP(6),
    fecha_modificacion_categoria TIMESTAMP(6),
    fecha_baja_categoria         TIMESTAMP(6)
);

CREATE TABLE cliente (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente                  VARCHAR(255),
    apellido_cliente                VARCHAR(255),
    telefono_cliente                VARCHAR(255),
    mail_cliente                    VARCHAR(255),
    fecha_hora_alta_cliente         TIMESTAMP(6),
    fecha_hora_modificacion_cliente TIMESTAMP(6),
    fecha_hora_baja_cliente         TIMESTAMP(6)
);

CREATE TABLE mueble (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_mueble      VARCHAR(255),
    color_mueble       VARCHAR(255),
    descripcion        VARCHAR(255),
    link_instagram     VARCHAR(255),
    link_facebook      VARCHAR(255),
    publicar           BOOLEAN NOT NULL DEFAULT FALSE,
    -- Las fechas de Mueble son String en la entidad
    fecha_alta         VARCHAR(255),
    fecha_modificacion VARCHAR(255),
    fecha_baja         VARCHAR(255),
    categoria_id       BIGINT,
    CONSTRAINT fk_mueble_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id)
);

CREATE TABLE mueble_imagenes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    es_portada      BOOLEAN NOT NULL,
    imagen_imagenes BYTEA,
    mueble_id       BIGINT,
    CONSTRAINT fk_mueble_imagenes_mueble FOREIGN KEY (mueble_id) REFERENCES mueble (id)
);

CREATE TABLE consulta (
    id                               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mensaje_consulta                 VARCHAR(255),
    fecha_hora_alta_consulta         TIMESTAMP(6),
    fecha_hora_modificacion_consulta TIMESTAMP(6),
    respuesta                        TEXT,
    cliente_id                       BIGINT NOT NULL,
    -- NULL = consulta general (formulario de contacto de la Home)
    mueble_id                        BIGINT,
    CONSTRAINT fk_consulta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_consulta_mueble FOREIGN KEY (mueble_id) REFERENCES mueble (id)
);

CREATE TABLE usuario (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username                   VARCHAR(255) NOT NULL,
    password                   VARCHAR(255),
    -- Enum Role guardado por ordinal: 0 = ADMIN, 1 = EMPLEADO, 2 = CLIENTE
    role                       SMALLINT CHECK (role BETWEEN 0 AND 2),
    fecha_alta_usuario         DATE,
    fecha_baja_usuario         DATE,
    fecha_modificacion_usuario DATE,
    cliente_id                 BIGINT,
    CONSTRAINT uk_usuario_username UNIQUE (username),
    CONSTRAINT uk_usuario_cliente UNIQUE (cliente_id),
    CONSTRAINT fk_usuario_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id)
);

-- Indices para las FK que se usan en filtros y joins (Postgres no los crea solo)
CREATE INDEX idx_mueble_categoria ON mueble (categoria_id);
CREATE INDEX idx_mueble_imagenes_mueble ON mueble_imagenes (mueble_id);
CREATE INDEX idx_consulta_cliente ON consulta (cliente_id);
CREATE INDEX idx_consulta_mueble ON consulta (mueble_id);
